package com.carddemo.vsam;

import java.util.List;
import java.util.stream.Collectors;

final class Ddl {

    private Ddl() {}

    static String migration(List<TableDef> tables, List<Cluster> clusters) {
        StringBuilder sql = new StringBuilder();
        sql.append("-- Generated by com.carddemo.vsam.SchemaGenerator. Do not edit.\n");
        for (int i = 0; i < tables.size(); i++) {
            sql.append('\n');
            appendTable(sql, tables.get(i), clusters.get(i));
        }
        sql.append('\n');
        for (TableDef table : tables) {
            for (ForeignKeyDef foreignKey : table.foreignKeys()) {
                sql.append("ALTER TABLE ").append(table.dataset().table())
                        .append(" ADD CONSTRAINT ").append(foreignKey.name())
                        .append(" FOREIGN KEY (").append(names(foreignKey.columns())).append(")")
                        .append(" REFERENCES ").append(foreignKey.parentTable())
                        .append(" (").append(String.join(", ", foreignKey.parentColumns())).append(");\n");
            }
        }
        return sql.toString();
    }

    static String typeName(SqlType type) {
        return switch (type) {
            case SqlType.Text text -> "varchar(" + text.length() + ")";
            case SqlType.Int ignored -> "integer";
            case SqlType.BigInt ignored -> "bigint";
            case SqlType.Numeric numeric -> "numeric(" + numeric.precision() + "," + numeric.scale() + ")";
            case SqlType.Date ignored -> "date";
            case SqlType.Timestamp ignored -> "timestamp(6)";
        };
    }

    private static void appendTable(StringBuilder sql, TableDef table, Cluster cluster) {
        String name = table.dataset().table();
        sql.append("CREATE TABLE ").append(name).append(" (\n");
        for (Column column : table.columns()) {
            sql.append("    ").append(columnDefinition(column)).append(",\n");
        }
        sql.append("    PRIMARY KEY (").append(names(table.primaryKey())).append(")\n");
        sql.append(");\n");
        sql.append("COMMENT ON TABLE ").append(name).append(" IS '")
                .append(escape(tableComment(table, cluster))).append("';\n");
        for (Column column : table.columns()) {
            sql.append("COMMENT ON COLUMN ").append(name).append('.').append(column.name())
                    .append(" IS '").append(escape(columnComment(column))).append("';\n");
        }
        for (IndexDef index : table.indexes()) {
            sql.append("CREATE ");
            if (index.unique()) {
                sql.append("UNIQUE ");
            }
            sql.append("INDEX ").append(index.name())
                    .append(" ON ").append(name)
                    .append(" (").append(names(index.columns())).append(");\n");
        }
    }

    private static String columnDefinition(Column column) {
        StringBuilder sql = new StringBuilder();
        sql.append(column.name()).append(' ').append(typeName(column.type()));
        if (column.type() instanceof SqlType.Text) {
            sql.append(" COLLATE \"C\"");
        }
        sql.append(" NOT NULL");
        switch (column.type()) {
            case SqlType.Int digits -> sql.append(range(column.name(), digits.digits()));
            case SqlType.BigInt digits -> sql.append(range(column.name(), digits.digits()));
            case SqlType.Numeric numeric when !numeric.signed() ->
                    sql.append(" CHECK (").append(column.name()).append(" >= 0)");
            default -> {
            }
        }
        return sql.toString();
    }

    private static String range(String name, int digits) {
        return " CHECK (" + name + " BETWEEN 0 AND " + "9".repeat(digits) + ")";
    }

    private static String tableComment(TableDef table, Cluster cluster) {
        return "cluster " + cluster.dsn()
                + ", copybook " + table.dataset().copybook()
                + ", record length " + table.layout().recordLength()
                + ", key offset " + cluster.key().offset()
                + " length " + cluster.key().length();
    }

    private static String columnComment(Column column) {
        Field field = column.field();
        return field.cobolName() + " PIC " + field.picClause()
                + " offset " + field.offset()
                + " length " + field.length();
    }

    private static String names(List<Column> columns) {
        return columns.stream().map(Column::name).collect(Collectors.joining(", "));
    }

    private static String escape(String text) {
        return text.replace("'", "''");
    }
}
