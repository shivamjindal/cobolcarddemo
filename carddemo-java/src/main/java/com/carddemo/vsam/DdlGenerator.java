package com.carddemo.vsam;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.stream.Collectors;

public final class DdlGenerator {

    private DdlGenerator() {
    }

    public static String generate() {
        return "-- Generated by DdlGenerator from the copybooks in app/cpy. Regenerate with ./gradlew generateDdl.\n\n"
                + Arrays.stream(VsamDataset.values())
                .map(d -> Table.of(d).ddl())
                .collect(Collectors.joining("\n"));
    }

    public static void main(String[] args) throws IOException {
        Path out = Path.of(args[0]);
        Files.writeString(out, generate());
        System.out.println("Wrote " + out);
    }
}
