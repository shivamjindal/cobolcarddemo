#!/usr/bin/env python3
"""Generate docs/migration/schema-mapping.md from copybooks + db_mapping.py + LISTCAT (dependency-map.json)."""
import json
from pathlib import Path

import copybook as cb
from db_mapping import CPY, RECORDS

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "docs" / "migration" / "schema-mapping.md"

HEADER = """# Schema mapping: VSAM KSDS to Postgres

Generated by `docs/migration/tools/gen_schema_mapping.py` from the copybooks, `db_mapping.py` and
`dependency-map.json`. The field tables are regenerated; the decisions below are edited in the script.
DDL: `db/migration/V1..V4`. Proof: `docs/migration/tools/run_validation.sh`.

## Data shape

Ten KSDS clusters become ten tables. Three alternate indexes become plain indexes. Customer and account are
linked only through `card_account_xref` (many-to-many in principle, one card per account in the sample data).

```
customers 1--* card_account_xref *--1 accounts 1--* cards 1--* transactions *--1 transaction_categories *--1 transaction_types
                    |__ card_num -> cards                  accounts 1--* transaction_category_balances
disclosure_groups(group_id, type_cd, cat_cd) -> transaction_categories      users (stand-alone)
```

## Decisions

| Topic | Decision | Why |
|---|---|---|
| `PIC X(n)` | `VARCHAR(n)`, trailing blanks stripped on load; `CHAR(n)` only for fixed-width flags and numeric-string identifiers (ssn, cvv, status flags) | COBOL pads to n; Postgres `CHAR(n)` pads too and surprises JPA and string equality, so it is limited to values that are always full width |
| `PIC 9(n)` identifiers | Account id `BIGINT` (11 digits), customer id `INTEGER` (9 digits), category code `INTEGER`. Card number, SSN, CVV stay strings | Leading zeros are meaningful for PAN, SSN and CVV. Numeric ids are zero-padded at the API edge |
| `PIC S9(n)V99` | `NUMERIC(n+2,2)`, never float | Money. Source data is zoned decimal with a trailing overpunch sign (`{`=+0, `A`-`I`=+1..9, `}`=-0, `J`-`R`=-1..-9); `db_mapping.decode_zoned` decodes it |
| `COMP` / `COMP-3` | None in the ten record copybooks. They appear only in `CVEXPORT` (the CBEXPORT/CBIMPORT interchange file) and in program working storage | Decoded and checked against the loaded rows in `validate_schema.py` (big-endian binary, packed decimal) |
| `REDEFINES` | None in the ten record copybooks. `CVEXPORT` has five variants over `EXPORT-RECORD-DATA` selected by `EXPORT-REC-TYPE` (`C` customer, `A` account, `X` xref, `T` transaction, `D` card). Not a table: it is an interchange format, so it maps to a discriminated union in the importer. Other REDEFINES (`CODATECN`, `CSUTLDWY`, `CSDAT01Y`, menu tables) are date/menu working storage and disappear in the rewrite | A table per redefined view would duplicate data. The union is a parsing concern, not a storage concern |
| Dates | `X(10)` `YYYY-MM-DD` to `DATE`; `X(26)` timestamps to `TIMESTAMP(6)` without zone | Source carries no zone. Revisit if the Java side needs instants |
| 88-levels | Y/N flags become `CHECK (col IN ('Y','N'))`; user type `CHECK IN ('A','U')`. Message-text 88s and AID-key 88s are UI state, not data | Data record copybooks have no 88-levels. The conditions live in programs (COACTUPC, COCRDUPC) and COCOM01Y |
| FICO range | DB allows 0..999; the 300..850 edit stays in application validation | COACTUPC edits 300..850 (`FICO-RANGE-IS-VALID`) but the shipped sample has a score of 274 |
| `FILLER` | Dropped, record padding to the fixed LRECL | No data. Row width no longer matters |
| Passwords | `users.password_hash`, bcrypt. Legacy `SEC-USR-PWD` is 8-char clear text compared after `UPPER-CASE` | Do not carry clear text into Postgres. Case-insensitive legacy passwords need a reset flow at cutover |
| Keys | KSDS primary key becomes the PK with the same column order. PK length and offset are asserted equal to LISTCAT | Browse order is the catch: VSAM orders keys by EBCDIC bytes, Postgres by collation. User and card list screens page by key, so use `ORDER BY ... COLLATE "C"` for ASCII byte order and accept that mixed letter/digit keys sort differently from the mainframe |
| Transaction id | PK is the 16-char numeric string; `transaction_id_seq` replaces max+1 minted by a backward browse in COTRN02C and COBIL00C | The browse race is a latent duplicate-key bug under concurrency |
| Referential integrity | VSAM has none. FKs are added where the data satisfies them (all do in the sample) | Application-enforced joins become declared constraints |

## Alternate indexes (LISTCAT and JCL) to indexes

| Legacy | Key | Online access | Postgres |
|---|---|---|---|
@@AIX@@

## Records

@@RECORDS@@
"""


def main():
    dm = json.loads((ROOT / "docs/migration/dependency-map.json").read_text())
    aix_rows = []
    desc = {
        "AWS.M2.CARDDEMO.CARDDATA.VSAM.AIX": ("CARD-ACCT-ID", "CARDAIX path in CICS file CARDAIX; COCRDSLC reads cards by account", "`cards_acct_id_idx`"),
        "AWS.M2.CARDDEMO.CARDXREF.VSAM.AIX": ("XREF-ACCT-ID", "CICS file CXACAIX; COACTVWC, COACTUPC, COBIL00C, COTRN02C resolve account to card", "`card_account_xref_acct_id_idx`"),
        "AWS.M2.CARDDEMO.TRANSACT.VSAM.AIX": ("TRAN-PROC-TS", "no CICS FILE definition and no program reads it; built by TRANIDX/TRANFILE JCL only", "`transactions_proc_ts_idx` (parity only)"),
    }
    for name, d in sorted(dm["listcat"].items()):
        if d["type"] == "AIX":
            fld, use, pg = desc[name]
            aix_rows.append(f"| {name.replace('AWS.M2.CARDDEMO.', '')} | {fld}, {d['key_length']} bytes at offset {d['key_offset']}, nonunique | {use} | {pg} |")
    blocks = []
    for rec in RECORDS:
        root = cb.record(ROOT / CPY / f"{rec.copybook}.cpy", rec.record)
        fields = {f.name: f for f in cb.flatten(root)}
        lc = dm["listcat"][f"AWS.M2.CARDDEMO.{rec.vsam}"]
        lines = [f"### `{rec.table}`", "",
                 f"Source: `{rec.copybook}` `{rec.record}` ({root.size} bytes) in `{rec.vsam}` "
                 f"(KSDS key {lc['key_length']} bytes at offset {lc['key_offset']}, {lc['records']} records cataloged). "
                 f"Primary key: `{', '.join(rec.pk)}`.", "",
                 "| COBOL field | Off | Len | PIC / usage | Column | Type | Null | Notes |", "|---|---|---|---|---|---|---|---|"]
        for c in rec.cols:
            f = fields[c.cobol]
            usage = f.pic + ("" if f.usage == "DISPLAY" else f" {f.usage}")
            lines.append(f"| {c.cobol} | {f.offset} | {f.size} | `{usage}` | `{c.column}` | {c.sql} | "
                         f"{'yes' if c.nullable else 'no'} | {c.note} |")
        dropped = [f for n, f in fields.items() if n not in {c.cobol for c in rec.cols}]
        for f in dropped:
            lines.append(f"| {f.name} | {f.offset} | {f.size} | `{f.pic}` | (dropped) | | | padding |")
        blocks.append("\n".join(lines))
    OUT.write_text(HEADER.replace("@@AIX@@", "\n".join(aix_rows)).replace("@@RECORDS@@", "\n\n".join(blocks)) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
